						if ( $category ) {
							$catlink
								= get_category_link( $category[0]->cat_ID );
							echo '<a href="' . esc_url( $catlink ) . '">'
							     . esc_html( $category[0]->cat_name )
							     . '</a> <span class="raquo"> /</span> ';
