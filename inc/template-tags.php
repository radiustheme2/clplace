if ( ! function_exists( 'clplace_post_meta' ) ) {
	/**
	 * Get post meta
	 *
	 * @return string
	 */
	function clplace_post_meta( $args ) {
		$default_args = [
			'with_list'     => true,
			'include'       => [],
			'class'         => '',
			'with_icon'     => false,
			'author_prefix' => __( 'By', 'clplace' )
		];

		$args = wp_parse_args( $args, $default_args );

		$comments_number = get_comments_number();
		$comments_text   = sprintf(
			_n( '%s Comment', '%s Comments', $comments_number, 'clplace' ),
			number_format_i18n( $comments_number )
		);

		$_meta_data = [];
		$output     = '';

		$_meta_data['author']   = clplace_posted_by( $args['author_prefix'] );
		$_meta_data['date']     = clplace_posted_on();
		$_meta_data['category'] = clplace_posted_in();
		$_meta_data['tag']      = clplace_posted_in( 'tag' );
		$_meta_data['comment']  = esc_html( $comments_text );

		$meta_list = $args['include'] ?? array_keys( $_meta_data );

		if ( $args['with_list'] ) {
			$output .= '<div class="clplace-post-meta ' . $args['class']
			           . '"><ul class="entry-meta">';
		}

		foreach ( $meta_list as $key ) {
			$meta = $_meta_data[ $key ];
			if ( ! $meta ) {
				continue;
			}
			$output .= ( $args['with_list'] ) ? '<li class="' . $key . '">' : '';
			$output .= $args['with_icon'] ? clplace_meta_icons( $key ) : null;
			$output .= $meta;
			$output .= ( $args['with_list'] ) ? '</li>' : '';
		}

		if ( $args['with_list'] ) {
			$output .= '</ul></div>';
		}

		return $output;
	}
}

