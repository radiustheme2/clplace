			$title = esc_html__( 'Search Results for : ', 'clplace' )
			         . get_search_query();
		} elseif ( is_home() ) {
			if ( get_option( 'page_for_posts' ) ) {
				$title = get_the_title( get_option( 'page_for_posts' ) );
			} else {
				$title = apply_filters( "rt_blog_title",
					esc_html__( 'All Posts', 'clplace' ) );
			}
		} elseif ( is_post_type_archive( 'rtcl_listing' ) ) {
			$title = apply_filters( "rt_listing_title",
				esc_html__( 'All Places', 'clplace' ) );
		} elseif ( is_post_type_archive( 'store' ) ) {
			$title = apply_filters( "rt_store_title",
				esc_html__( 'All Stores', 'clplace' ) );
		} elseif ( is_post_type_archive( 'product' ) ) {
			$title = apply_filters( "rt_shop_title",
				esc_html__( 'Shop', 'clplace' ) );
		} elseif ( is_archive() ) {
			$title = get_the_archive_title();
		} elseif ( is_page() ) {
			$title = get_the_title();
		} else {
			$title = get_the_title();
		}

		echo wp_kses_post( $title );
	}
}

