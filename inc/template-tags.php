	/**
	 * Get File Path
	 *
	 * @param $path
	 *
	 * @return string
	 */
	function clplace_get_file( $path, $return_path = false ): string {
		$file = ( $return_path ? get_stylesheet_directory()
				: get_stylesheet_directory_uri() ) . $path;
		if ( ! file_exists( $file ) ) {
