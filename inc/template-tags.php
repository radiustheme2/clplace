/**
 * Comments FDF
 */
function clplace_comments_cbf( $comment, $args, $depth ) {

	// Get correct tag used for the comments
	if ( 'div' === $args['style'] ) {
		$tag       = 'div ';
		$add_below = 'comment';
	} else {
		$tag       = 'li ';
		$add_below = 'div-comment';
	} ?>

    <<?php echo wp_kses_post( $tag ); ?><?php comment_class(
		empty( $args['has_children'] ) ? '' : 'parent'
	); ?> id="comment-<?php comment_ID() ?>">

	<?php
	// Switch between different comment types
	switch ( $comment->comment_type ) :
		case 'pingback' :
		case 'trackback' : ?>
            <div class="pingback-entry"><span
                        class="pingback-heading"><?php esc_html_e(
						'Pingback:', 'clplace'
					); ?></span> <?php comment_author_link(); ?></div>
			<?php
			break;
		default :

			if ( 'div' != $args['style'] ) { ?>
                <div id="div-comment-<?php comment_ID() ?>" class="comment-body">
			<?php } ?>
            <div class="comment-author">
                <div class="vcard">
					<?php
					// Display avatar unless size is set to 0
					if ( $args['avatar_size'] != 0 ) {
						$avatar_size = ! empty( $args['avatar_size'] )
							? $args['avatar_size']
							: 70; // set default avatar size
						echo get_avatar( $comment, $avatar_size );
					} ?>
                </div>
                <div class="meta-with-text">
                    <div class="author-info">
						<?php
						// Display author name
						printf(
							esc_html__( '<cite class="fn">%s</cite>', 'clplace' ),
							get_comment_author_link()
						); ?>

                        <div class="comment-meta commentmetadata">
                            <a href="<?php echo esc_url(
								get_comment_link( $comment->comment_ID )
							); ?>"><?php
								/* translators: 1: date, 2: time */
								printf(
									esc_html__( '%1$s at %2$s', 'clplace' ),
									esc_html( get_comment_date() ),
									esc_html( get_comment_time() )
								); ?>
                            </a><?php
							edit_comment_link(
								__( 'Edit', 'clplace' ), '  ', ''
							); ?>
                        </div><!-- .comment-meta -->
                    </div>
                    <div class="comment-text"><?php comment_text(); ?></div>
                </div>
            </div><!-- .comment-author -->
            <div class="comment-details">
                <!-- .comment-text -->
				<?php
				// Display comment moderation text
				if ( $comment->comment_approved == '0' ) { ?>
                    <em class="comment-awaiting-moderation"><?php esc_html_e(
							'Your comment is awaiting moderation.',
							'clplace'
						); ?></em><br/><?php
				} ?>

				<?php
				$icon = '<i class="icon-reply"></i>';
				// Display comment reply link
				comment_reply_link( array_merge( $args, [
					'add_below'  => $add_below,
					'depth'      => $depth,
					'max_depth'  => $args['max_depth'],
					'reply_text' => $icon
				] ) ); ?>

            </div><!-- .comment-details -->
			<?php
			if ( 'div' != $args['style'] ) { ?>
                </div>
			<?php }
			// IMPORTANT: Note that we do NOT close the opening tag, WordPress does this for us
			break;
	endswitch; // End comment_type check.
}
