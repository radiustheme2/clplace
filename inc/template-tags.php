if ( ! function_exists( 'clplace_reading_time' ) ) {
	/**
	 * Post reading time
	 * @return string
	 */
	function clplace_reading_time() {
		$post_content = get_post()->post_content;
		$post_content = strip_shortcodes( $post_content );
		$post_content = strip_tags( $post_content );
		$word_count   = str_word_count( $post_content );
		$reading_time = floor( $word_count / 200 );

		if ( $reading_time < 1 ) {
			$result = esc_html__( 'Less than a minute', 'clplace' );
		} elseif ( $reading_time > 60 ) {
			$result = sprintf( esc_html__( '%s hours read', 'clplace' ), floor( $reading_time / 60 ) );
		} else if ( $reading_time == 1 ) {
			$result = esc_html__( '1 min read', 'clplace' );
		} else {
			$result = sprintf( esc_html__( '%s mins read', 'clplace' ), $reading_time );
		}

		return '<span class="meta-reading-time meta-item">' . $result . '</span> ';
	}

}

