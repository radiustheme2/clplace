if ( ! function_exists( 'clplace_posted_in' ) ) {
	/**
	 * Prints HTML with category list information about theme categories.
	 *
	 * @return string
	 */
	function clplace_posted_in( $type = 'category' ) {
		$categories_list = get_the_category_list(
			clplace_list_item_separator()
		);
		if ( 'tag' === $type ) {
			$categories_list = get_the_tag_list(
				'', clplace_list_item_separator()
			);
		}
		if ( $categories_list ) {
			return sprintf(
				'<span class="%s-links">%s</span>',
				$type,
				$categories_list
			);
		}

		return '';
	}
}

